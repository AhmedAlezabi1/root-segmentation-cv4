_SECURE_COOKIES = os.environ.get("CV4_ENV") != "development"


def _set_auth_cookies(response: Response, user_id: int, email: str) -> None:
    """Write access and refresh JWTs as httpOnly cookies onto *response*.

    Both cookies are:
    - ``HttpOnly`` — not readable by JavaScript
    - ``SameSite=Lax`` — sent on same-site navigations; blocks CSRF for
      mutating requests
    - ``Secure`` — HTTPS only, disabled when ``CV4_ENV=development``

    Parameters
    ----------
    response : Response
        The FastAPI ``Response`` object to attach cookies to.
    user_id : int
        The authenticated user's primary key.
    email : str
        The authenticated user's email address.
    """
    access_token = create_access_token(user_id, email)
    refresh_token = create_refresh_token(user_id, email)

    response.set_cookie(
        key="access_token",
        value=access_token,
        httponly=True,
        samesite="lax",
        secure=_SECURE_COOKIES,
        max_age=ACCESS_TOKEN_EXPIRE_MINUTES * 60,
        path="/",
    )
    response.set_cookie(
        key="refresh_token",
        value=refresh_token,
        httponly=True,
        samesite="lax",
        secure=_SECURE_COOKIES,
        max_age=REFRESH_TOKEN_EXPIRE_DAYS * 24 * 60 * 60,
        # Scope the refresh token to its dedicated endpoint only, limiting
        # the blast radius if the cookie is somehow forwarded elsewhere.
        path="/",
    )


