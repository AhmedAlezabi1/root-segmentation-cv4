class RootTipPx(BaseModel):
    """Pixel coordinates of the detected root tip within the cropped plate space.

    The coordinate origin (0, 0) is the top-left corner of the petri dish
    crop produced by the preprocessing step. These coordinates are NOT
    relative to the original full image.

    Both fields are integer pixel indices. Subpixel localisation is not
    performed by the current pipeline.
    """

    x: int = Field(..., description="Tip x-coordinate in pixels (horizontal, left=0).")
    y: int = Field(..., description="Tip y-coordinate in pixels (vertical, top=0).")


class RootResult(BaseModel):
    """Segmentation and localisation measurements for a single plant lane.

    One ``RootResult`` is produced per lane regardless of whether a root
    was detected. Consumers must check ``has_root`` before using
    ``root_tip_px`` and ``confidence``, as both are ``None`` for empty lanes.

    Lanes are numbered 0-4 left to right as they appear in the petri dish
    image after cropping.
    """

    lane: int = Field(
        ...,
        description="0-indexed lane number, left to right across the petri dish.",
    )
    has_root: bool = Field(
        ...,
        description=("True if the pipeline detected a root in this lane. When False, root_tip_px and confidence are None."),
    )
    root_tip_px: RootTipPx | None = Field(
        None,
        description=("Pixel coordinates of the root tip in plate/crop space. None when has_root is False."),
    )
    confidence: float | None = Field(
        None,
        ge=0.0,
        le=1.0,
        description=(
            "Model probability at the root tip pixel, in the range [0, 1]. "
            "Derived from the raw UNet output (sigmoid probability map) at the "
            "localised tip coordinate. None when has_root is False."
        ),
    )


class PredictResponse(BaseModel):
    """Complete response body returned by a successful POST /predict request.

    Always contains exactly 5 ``RootResult`` entries (one per lane), even if
    some lanes contain no detected root. This uniform structure simplifies
    downstream parsing - consumers iterate over all 5 entries and filter
    by ``has_root``. The prediction_id can be used to submit feedback via
    POST /feedback.
    """

    prediction_id: int = Field(
        ...,
        description="Database ID of this prediction. Pass to POST /feedback to submit corrections.",
    )
    roots: list[RootResult] = Field(
        ...,
        description="Per-lane results. Always contains exactly 5 entries (lanes 0-4).",
    )
    processing_time_s: float = Field(
        ...,
        description="End-to-end wall-clock time in seconds, measured inside run_pipeline.",
    )
    crop: CropBox = Field(
        ...,
        description=(
            "Bounding box of the petri dish crop within the original image. "
            "Add crop.x / crop.y to root_tip_px coordinates to get original-image pixel positions."
        ),
    )


