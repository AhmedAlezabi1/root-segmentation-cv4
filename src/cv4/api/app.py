@app.post(
    "/feedback/{prediction_id}/image",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Store the source image for a prediction that has received feedback",
    tags=["Feedback"],
    responses={
        status.HTTP_404_NOT_FOUND: {
            "description": "Prediction ID does not exist in the database.",
            "model": ErrorResponse,
        },
        status.HTTP_400_BAD_REQUEST: {
            "description": "Uploaded file is not an image.",
            "model": ErrorResponse,
        },
    },
)
async def store_feedback_image(
    prediction_id: int,
    image: UploadFile = File(...),
    _user: User = Depends(get_current_user),
    db: Session = Depends(get_session),
) -> None:
    """Save the original image for a prediction that has received feedback.

    Called by the frontend immediately after a successful POST /feedback
    submission. Stores the image on disk under ``FEEDBACK_IMAGE_DIR`` and
    records the path in the ``feedback_images`` table. The call is idempotent:
    re-uploading for the same ``prediction_id`` overwrites the previous file
    and updates the database row.

    Images are stored as ``{prediction_id}{original_extension}`` to keep
    filenames filesystem-safe. The original client filename is preserved in
    the database for display purposes.

    Parameters
    ----------
    prediction_id : int
        ID of the prediction the image belongs to. Must exist in the database.
    image : UploadFile
        Multipart image upload. Must have a content-type starting with
        ``image/``.
    _user : User
        Auth result injected by ``get_current_user``. Not used directly.
    db : Session
        Database session injected by ``Depends(get_session)``.

    Returns
    -------
    None
        HTTP 204 No Content on success.

    Raises
    ------
    HTTPException 404
        If ``prediction_id`` does not exist.
    HTTPException 400
        If the uploaded file is not an image.
    """
    ALLOWED_CONTENT_TYPES = {"image/png", "image/jpeg", "image/tiff", "image/tif"}
    content_type = image.content_type or ""
    if not content_type.startswith("image/") or content_type not in ALLOWED_CONTENT_TYPES:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=(f"Expected an image file ({', '.join(sorted(ALLOWED_CONTENT_TYPES))}), got '{content_type or 'unknown'}'."),
        )

    prediction = db.get(Prediction, prediction_id)
    if prediction is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Prediction {prediction_id} not found.",
        )

    # Derive a safe filename: {prediction_id}{extension}
    original_name = image.filename or "upload"
    ext = os.path.splitext(original_name)[1] or ".png"
    stored_filename = f"{prediction_id}{ext}"
    stored_path = FEEDBACK_IMAGE_DIR / stored_filename

    # Write the image to disk, replacing any previous upload for this prediction.
    try:
        with stored_path.open("wb") as f:
            await asyncio.to_thread(shutil.copyfileobj, image.file, f)
    except OSError as exc:
        logger.exception("Failed to write feedback image for prediction %d: %s", prediction_id, exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to save image. See server logs.",
        ) from exc

    # Upsert the feedback_images row.
    from sqlalchemy import select as sa_select  # local import to avoid top-level pollution

    existing = db.execute(sa_select(FeedbackImage).where(FeedbackImage.prediction_id == prediction_id)).scalar_one_or_none()

    if existing is None:
        db.add(
            FeedbackImage(
                prediction_id=prediction_id,
                original_filename=original_name,
                stored_path=str(stored_path),
                content_type=content_type,
            )
        )
    else:
        existing.original_filename = original_name
        existing.stored_path = str(stored_path)
        existing.content_type = content_type
        existing.updated_at = __import__("datetime").datetime.now(__import__("datetime").timezone.utc)

    db.commit()
    logger.info("Stored feedback image for prediction %d at %s", prediction_id, stored_path)


@app.get(
    "/feedback/export",
    summary="Download a ZIP of all images that have received feedback",
    tags=["Feedback"],
    responses={
        status.HTTP_404_NOT_FOUND: {
            "description": "No feedback images have been stored yet.",
            "model": ErrorResponse,
        },
    },
    response_class=StreamingResponse,
)
async def export_feedback_images(
    _user: User = Depends(get_current_user),
    db: Session = Depends(get_session),
) -> StreamingResponse:
    """Return a ZIP archive containing all stored feedback images.

    Queries the ``feedback_images`` table for every prediction that has had
    an image stored via ``POST /feedback/{prediction_id}/image``, reads each
    file from disk, and bundles them into a single ZIP. Each file inside the
    archive is named ``prediction_{id}_{original_filename}`` so the contents
    are immediately identifiable.

    Missing files (deleted from disk after the DB row was written) are
    silently skipped and logged as warnings rather than failing the whole
    export.

    Parameters
    ----------
    _user : User
        Auth result injected by ``get_current_user``. Not used directly.
    db : Session
        Database session injected by ``Depends(get_session)``.

    Returns
    -------
    StreamingResponse
        ``application/zip`` stream. ``Content-Disposition`` header sets the
        download filename to ``cv4-feedback-images-{date}.zip``.

    Raises
    ------
    HTTPException 404
        If no feedback images have been stored yet.
    """
    from datetime import datetime as _dt
    from datetime import timezone as _tz

    from sqlalchemy import select as sa_select  # local import to avoid top-level pollution

    rows = db.execute(sa_select(FeedbackImage)).scalars().all()

    if not rows:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No feedback images have been stored yet.",
        )

    buf = io.BytesIO()
    included = 0
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for row in rows:
            try:
                with open(row.stored_path, "rb") as f:
                    data = f.read()
            except FileNotFoundError:
                logger.warning(
                    "Feedback image file missing for prediction %d (expected at %s); skipping.",
                    row.prediction_id,
                    row.stored_path,
                )
                continue
            arcname = f"prediction_{row.prediction_id}_{row.original_filename}"
            zf.writestr(arcname, data)
            included += 1

    if included == 0:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No feedback image files found on disk.",
        )

    buf.seek(0)
    today = _dt.now(_tz.utc).strftime("%Y-%m-%d")
    download_name = f"cv4-feedback-images-{today}.zip"

    logger.info("Exporting %d feedback image(s) as %s", included, download_name)

    return StreamingResponse(
        buf,
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{download_name}"'},
    )


