@asynccontextmanager
async def lifespan(app: FastAPI):
    """Manage the application lifespan: set up the inference backend on startup.

    FastAPI calls this async context manager once when the server starts.

    **Local mode** (``CV4_INFERENCE_MODE=local``, the default):
        The cv4 UNet model is loaded here — not inside the request handler —
        so the ~30 s TensorFlow cold-load cost is paid once at startup rather
        than on the first request.  The loaded model is stored in
        ``app.state.model``.  If loading fails, ``app.state.model`` is set to
        ``None`` and the error is logged.  The server continues running in a
        degraded state: ``/health`` returns 503 and ``/predict`` returns 503,
        but the process stays alive so orchestrators can observe the failure
        and restart the container.

    **Remote mode** (``CV4_INFERENCE_MODE=remote``):
        No local model is loaded.  Instead, an ``AzureMLEndpointClient`` is
        configured from ``AZURE_ML_ENDPOINT_URL`` and ``AZURE_ML_ENDPOINT_KEY``
        and stored in ``app.state.endpoint_client``.  If either variable is
        missing, the client is not created and the service starts in a
        degraded state (503 on ``/health`` and ``/predict``).  The ~30 s
        model-load cost is avoided entirely.

    In both modes ``app.state.inference_mode`` is set to the resolved mode
    string (``"local"`` or ``"remote"``), which the request handlers use to
    select the right backend at request time.

    Parameters
    ----------
    app : FastAPI
        The application instance. ``app.state`` is used as a namespace
        for startup-time shared state.
    """
    inference_mode = os.environ.get("CV4_INFERENCE_MODE", "local").strip().lower()
    # Normalise unrecognised values to "local" with a warning
    if inference_mode not in ("local", "remote"):
        logger.warning(
            "Unrecognised CV4_INFERENCE_MODE=%r; falling back to 'local'.",
            inference_mode,
        )
        inference_mode = "local"

    app.state.inference_mode = inference_mode

    # Ensure the feedback image storage directory exists.
    # Parents=True so nested paths (e.g. /data/cv4/feedback_images) are
    # created in one call; exist_ok=True makes the call idempotent.
    FEEDBACK_IMAGE_DIR.mkdir(parents=True, exist_ok=True)
    logger.info("Feedback image storage: %s", FEEDBACK_IMAGE_DIR)

    if inference_mode == "remote":
        # ------------------------------------------------------------------
        # Remote mode: configure the Azure ML endpoint client
        # ------------------------------------------------------------------
        endpoint_url = os.environ.get("AZURE_ML_ENDPOINT_URL", "").strip()
        endpoint_key = os.environ.get("AZURE_ML_ENDPOINT_KEY", "").strip()
        timeout_s = float(os.environ.get("CV4_ENDPOINT_TIMEOUT_S", "30.0"))
        deployment_name = os.environ.get("AZURE_ML_DEPLOYMENT_NAME", "").strip() or None

        if not endpoint_url or not endpoint_key:
            logger.error(
                "CV4_INFERENCE_MODE=remote requires both AZURE_ML_ENDPOINT_URL "
                "and AZURE_ML_ENDPOINT_KEY to be set. "
                "The service will start but /predict will return 503 until "
                "the variables are provided and the container is restarted."
            )
            app.state.model = None
            app.state.endpoint_client = None
        else:
            app.state.model = None  # Not used in remote mode
            app.state.endpoint_client = AzureMLEndpointClient(
                url=endpoint_url,
                key=endpoint_key,
                timeout_s=timeout_s,
                deployment_name=deployment_name,
            )
            logger.info(
                "Remote inference configured (endpoint=%r deployment=%r timeout=%.0fs).",
                endpoint_url,
                deployment_name,
                timeout_s,
            )
    else:
        # ------------------------------------------------------------------
        # Local mode (default): load the cv4 UNet model into memory
        # ------------------------------------------------------------------
        app.state.endpoint_client = None  # Not used in local mode
        logger.info("Loading model (CV4_INFERENCE_MODE=local)...")
        try:
            app.state.model = load_model()
            logger.info("Model loaded successfully.")
        except (FileNotFoundError, ValueError) as exc:
            # FileNotFoundError: weights file missing at DEFAULT_MODEL_PATH
            # ValueError: weights file exists but is corrupt or incompatible
            logger.error("Failed to load model: %s", exc)
            app.state.model = None

    yield
    # No teardown required — TensorFlow sessions are cleaned up by the process
    # and the httpx client used by AzureMLEndpointClient has no persistent connections.


