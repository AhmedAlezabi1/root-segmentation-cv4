@app.post(
    "/auth/register",
    response_model=UserResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Register a new user account",
    tags=["Auth"],
    responses={
        status.HTTP_409_CONFLICT: {
            "description": "Email address is already registered.",
            "model": ErrorResponse,
        },
    },
)
def register(
    body: UserCreate,
    db: Session = Depends(get_session),
) -> UserResponse:
    """Create a new user account.

    The password is hashed with PBKDF2-HMAC-SHA256 before storage.
    The plain-text password is never persisted or logged.

    Parameters
    ----------
    body : UserCreate
        ``{email, password, password_confirm}`` — passwords must match
        and be 8–128 characters long.

    Returns
    -------
    UserResponse
        The newly created user (id, email, is_active). HTTP 201.

    Raises
    ------
    HTTPException
        ``409 Conflict`` if the email address is already registered.
    """
    user = User(
        email=body.email.strip().lower(),
        hashed_password=hash_password(body.password),
    )
    db.add(user)
    try:
        db.commit()
        db.refresh(user)
    except IntegrityError:
        db.rollback()
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="An account with that email address already exists.",
        )
    return UserResponse.model_validate(user)


@app.post(
    "/auth/login",
    response_model=TokenResponse,
    summary="Log in and receive JWT cookies",
    tags=["Auth"],
    responses={
        status.HTTP_401_UNAUTHORIZED: {
            "description": "Invalid email or password.",
            "model": ErrorResponse,
        },
    },
)
def login(
    body: UserLogin,
    response: Response,
    db: Session = Depends(get_session),
) -> TokenResponse:
    """Authenticate a user and issue httpOnly JWT cookies.

    On success, two httpOnly cookies are set:

    - ``access_token`` — short-lived (default 30 min), sent on every request
    - ``refresh_token`` — long-lived (default 7 days), scoped to ``/auth/refresh``

    Parameters
    ----------
    body : UserLogin
        ``{email, password}``

    Returns
    -------
    TokenResponse
        ``{token_type: "bearer", user: {id, email, is_active}}`` with HTTP 200
        and the two auth cookies set.

    Raises
    ------
    HTTPException
        ``401 Unauthorized`` if the credentials are wrong or the account
        is disabled. The error is deliberately generic to avoid leaking
        whether the email exists.
    """
    _invalid = HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Invalid email or password.",
    )

    user = db.query(User).filter(User.email == body.email.strip().lower()).first()

    # Always run verify_password even on a miss to prevent a timing
    # side-channel that would reveal whether an email is registered.
    dummy_hash = "pbkdf2_sha256$600000$00$00"
    stored = user.hashed_password if user else dummy_hash
    if not verify_password(body.password, stored) or user is None:
        raise _invalid
    if not user.is_active:
        raise _invalid

    _set_auth_cookies(response, user.id, user.email)
    return TokenResponse(user=UserResponse.model_validate(user))


@app.post(
    "/auth/refresh",
    response_model=TokenResponse,
    summary="Rotate JWT cookies using the refresh token",
    tags=["Auth"],
    responses={
        status.HTTP_401_UNAUTHORIZED: {
            "description": "Refresh token is missing, invalid, or expired.",
            "model": ErrorResponse,
        },
    },
)
def refresh(
    response: Response,
    refresh_token: str | None = Cookie(default=None),
    db: Session = Depends(get_session),
) -> TokenResponse:
    """Issue a new access token (and rotate the refresh token) using the
    long-lived refresh token cookie.

    Call this endpoint when an authenticated request returns 401. If the
    refresh token is still valid, both cookies are replaced with fresh ones.
    If it has expired the user must log in again.

    Returns
    -------
    TokenResponse
        New cookies set; body mirrors ``/auth/login``.

    Raises
    ------
    HTTPException
        ``401 Unauthorized`` if the cookie is absent or the token is invalid.
    """
    if not refresh_token:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="No refresh token.")

    payload = decode_token(refresh_token, expected_type="refresh")
    user_id: int | None = payload.get("user_id")
    if user_id is None:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token payload.")

    user = db.get(User, user_id)
    if user is None or not user.is_active:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="User not found or disabled.")

    _set_auth_cookies(response, user.id, user.email)
    return TokenResponse(user=UserResponse.model_validate(user))


@app.post(
    "/auth/logout",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Clear JWT cookies and end the session",
    tags=["Auth"],
)
def logout(response: Response) -> None:
    """Expire both auth cookies immediately.

    Returns
    -------
    None
        HTTP 204 No Content.
    """
    response.delete_cookie("access_token", path="/")
    response.delete_cookie("refresh_token", path="/auth/refresh")


