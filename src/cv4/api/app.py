@app.post(
    "/feedback",
    response_model=FeedbackResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Submit feedback for a prediction",
    tags=["Feedback"],
    responses={
        status.HTTP_404_NOT_FOUND: {
            "description": "Prediction ID does not exist in the database.",
            "model": ErrorResponse,
        },
    },
)
async def submit_feedback(
    body: FeedbackRequest,
    _user: User = Depends(get_current_user),
    db: Session = Depends(get_session),
) -> FeedbackResponse:
    """Submit per-lane corrections for a stored prediction.

    Accepts a prediction ID and a list of per-lane feedback entries.
    Creates one ``feedback`` row per lane in the database and returns
    the generated IDs.

    A correction (``is_correct=False``) requires both ``correct_tip_x``
    and ``correct_tip_y`` — this is validated by the ``LaneFeedback``
    Pydantic model before this function runs.

    Parameters
    ----------
    body : FeedbackRequest
        JSON request body containing the prediction ID and lane feedback list.
    _user : User
        Auth result injected by ``get_current_user`` dependency. Not used directly.
    db : Session
        Database session injected by ``Depends(get_session)``.

    Returns
    -------
    FeedbackResponse
        HTTP 201 with the prediction ID and per-lane feedback IDs.

    Raises
    ------
    HTTPException 404
        If the prediction ID does not exist in the database.
    HTTPException 400
        If request body validation fails (handled by FastAPI/Pydantic
        before this function runs).
    """
    # Verify the referenced prediction exists before inserting feedback rows
    prediction = db.get(Prediction, body.prediction_id)
    if prediction is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Prediction {body.prediction_id} not found.",
        )

    # Insert one feedback row per submitted lane.
    # Wrapped in try/except so a database error rolls back the partial
    # transaction cleanly and returns a 500 rather than leaving orphaned rows.
    submitted = []
    try:
        for lane_fb in body.lanes:
            fb = Feedback(
                prediction_id=body.prediction_id,
                lane=lane_fb.lane,
                is_correct=lane_fb.is_correct,
                predicted_tip_x=lane_fb.predicted_tip_x,
                predicted_tip_y=lane_fb.predicted_tip_y,
                correct_tip_x=lane_fb.correct_tip_x if not lane_fb.is_correct else None,
                correct_tip_y=lane_fb.correct_tip_y if not lane_fb.is_correct else None,
                comment=lane_fb.comment,
            )
            db.add(fb)
            db.flush()  # flush to get the auto-generated id before commit
            submitted.append(FeedbackLaneResult(lane=lane_fb.lane, feedback_id=fb.id))

        db.commit()
    except Exception as exc:
        db.rollback()
        logger.exception("Failed to save feedback for prediction %d: %s", body.prediction_id, exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to save feedback. See server logs.",
        ) from exc

    logger.info(
        "Feedback submitted for prediction %d: %d lane(s)",
        body.prediction_id,
        len(submitted),
    )

    return FeedbackResponse(prediction_id=body.prediction_id, submitted=submitted)


