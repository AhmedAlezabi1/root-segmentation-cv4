"""
api/app.py
==========
FastAPI application for the cv4 plant root segmentation pipeline.

This module is the sole entry point for external HTTP access to the cv4
inference system. It is responsible for:

    - Receiving image uploads from clients over HTTP
    - Authenticating requests via JWT httpOnly cookie
    - Delegating inference to ``cv4.pipeline.run_pipeline``
    - Serialising the pipeline result into a validated JSON response
    - Returning structured error responses for all failure modes

It does NOT contain any algorithm logic. Every computational step
(preprocessing, inference, postprocessing, segmentation, localisation)
is owned by the pipeline module and its dependencies.

Endpoints
---------
POST /auth/register
    Create a new user account.

POST /auth/login
    Authenticate with email + password; receive httpOnly JWT cookies.

POST /auth/refresh
    Rotate both JWT cookies using the long-lived refresh token cookie.

POST /auth/logout
    Expire both auth cookies immediately.

GET /auth/me
    Return the profile of the currently authenticated user.

POST /predict
    Accept a multipart image upload, run the full segmentation pipeline,
    return per-plant root measurements as JSON. Stores the prediction in
    the database and returns the prediction ID. Requires authentication.

POST /feedback
    Submit per-lane corrections for a stored prediction. Requires
    authentication. Returns 201 with the generated feedback IDs.

GET /health
    Liveness and readiness check. Returns 200 when the model is loaded
    and ready to serve requests, 503 when the model failed to load at
    startup. Used by Docker HEALTHCHECK and container orchestrators
    (Portainer, Azure Container Apps) to gate traffic routing.

GET /docs
    Interactive Swagger UI, auto-generated by FastAPI from the route
    definitions and Pydantic schemas in this file. No code required.

GET /redoc
    ReDoc documentation view, also auto-generated by FastAPI.

Environment variables
---------------------
CV4_ENV : str, optional
    Set to "development" for local, non-HTTPS development. In development
    mode the auth cookies are not marked Secure (so they work over plain
    HTTP on localhost) and, if JWT_SECRET_KEY is unset, a random per-process
    development JWT secret is used. Never set this in production: production
    must use HTTPS-only Secure cookies and a real JWT_SECRET_KEY.

    CV4_ENV does NOT enable any API-key authentication. Authentication is
    JWT-only (see cv4.api.auth); there is no API-key scheme.

JWT_SECRET_KEY : str, required in non-development environments
    Secret used to sign all JWT tokens. Generate with:
    python -c "import secrets; print(secrets.token_hex(32))"

DATABASE_URL : str, optional
    SQLAlchemy connection string. Defaults to sqlite:///./feedback.db.
    See cv4.api.database for supported formats.

CV4_INFERENCE_MODE : str, optional
    Controls where UNet inference runs.  Accepted values:

    ``"local"`` (default)
        Inference runs in-process using the cv4 UNet model loaded at
        startup.  All other pipeline stages (preprocessing, postprocessing,
        segmentation, localisation) also run locally.  Behaviour is
        identical to the original implementation.

    ``"remote"``
        Inference is delegated to the Azure ML Managed Endpoint specified
        by ``AZURE_ML_ENDPOINT_URL`` / ``AZURE_ML_ENDPOINT_KEY``.
        Preprocessing, postprocessing, segmentation, and localisation
        continue to run locally inside the cv4 package; only the UNet
        forward pass moves to the endpoint.  The local model is not loaded
        at startup, so there is no ~30 s cold-load cost.

AZURE_ML_ENDPOINT_URL : str, required when CV4_INFERENCE_MODE=remote
    Full scoring URI of the Azure ML Managed Endpoint, e.g.
    ``https://<endpoint-name>.<region>.inference.ml.azure.com/score``.

AZURE_ML_ENDPOINT_KEY : str, required when CV4_INFERENCE_MODE=remote
    Primary or secondary endpoint key used as the Bearer token in the
    ``Authorization`` header.  Rotate in Azure ML Studio if compromised.

CV4_ENDPOINT_TIMEOUT_S : float, optional
    Per-request timeout in seconds for endpoint calls.  Defaults to 30.
    Increase if large images consistently time out.

AZURE_ML_DEPLOYMENT_NAME : str, optional
    Named deployment to route inference traffic to (e.g. ``"blue"`` or
    ``"green"``).  When set, every request carries an
    ``azureml-model-deployment`` header so Azure ML routes to that
    deployment instead of applying its default traffic-split rules.  This
    is the mechanism used by Issue 4.2 for blue/green model-version
    switching.  Omit to use Azure ML's default routing.

Dependencies
------------
cv4.inference.load_model
    Called once at startup to load the UNet weights into memory when
    ``CV4_INFERENCE_MODE=local`` (the default).  The loaded model is
    stored in ``app.state.model`` and reused for every subsequent request
    to avoid the ~30 s cold-load cost.  Not called in remote mode.

cv4.pipeline.run_pipeline
    Called once per request inside ``POST /predict``. Accepts an image
    file path and a callable model; returns a dict of per-plant
    measurements.  In remote mode the ``AzureMLEndpointClient`` is passed
    as the model argument — its ``__call__`` signature is compatible with
    the local cv4 model so the pipeline requires no changes.

cv4.api.endpoint.AzureMLEndpointClient
    HTTP client for the Azure ML Managed Endpoint.  Instantiated at
    startup when ``CV4_INFERENCE_MODE=remote`` and stored in
    ``app.state.endpoint_client``.  See ``cv4.api.endpoint`` for the
    wire-format specification and error-handling contract.
"""

