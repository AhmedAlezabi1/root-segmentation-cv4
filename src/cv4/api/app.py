@app.get(
    "/health",
    response_model=HealthResponse,
    summary="Liveness / readiness check",
    tags=["Monitoring"],
    responses={
        status.HTTP_503_SERVICE_UNAVAILABLE: {
            "description": ("Service is not ready: model failed to load (local mode) or endpoint is not configured (remote mode)."),
            "model": ErrorResponse,
        },
    },
)
async def health() -> HealthResponse:
    """Return service status and inference-backend readiness.

    This endpoint serves as both a liveness check (is the process alive?)
    and a readiness check (is the inference backend ready to serve?).

    **Local mode** (``CV4_INFERENCE_MODE=local``):
        HTTP 200 when the cv4 UNet model is loaded (``model_loaded=True``).
        HTTP 503 when the model failed to load at startup.

    **Remote mode** (``CV4_INFERENCE_MODE=remote``):
        HTTP 200 when the Azure ML endpoint client is configured
        (``model_loaded=False``, ``inference_mode="remote"``).
        HTTP 503 when ``AZURE_ML_ENDPOINT_URL`` or ``AZURE_ML_ENDPOINT_KEY``
        were not set at startup.
        Note: this check verifies configuration only; it does not ping the
        endpoint, so a 200 response does not guarantee the endpoint is
        currently reachable.

    Docker HEALTHCHECK and container orchestrators (Portainer, Azure
    Container Apps) use this endpoint to decide whether to route traffic
    to this container. Returning 503 instead of 200 prevents requests from
    being sent to a container that would immediately fail ``/predict``.

    Does not require authentication — orchestrators and load balancers
    must be able to reach this endpoint without credentials.

    Returns
    -------
    HealthResponse
        ``{"status": "ok", "model_loaded": <bool>, "inference_mode": <str>}``
        with HTTP 200.

    Raises
    ------
    HTTPException
        ``503 Service Unavailable`` if the inference backend is not ready.
    """
    inference_mode = getattr(app.state, "inference_mode", "local")

    if inference_mode == "remote":
        endpoint_client = getattr(app.state, "endpoint_client", None)
        if endpoint_client is None:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail=("Remote endpoint is not configured. Set AZURE_ML_ENDPOINT_URL and AZURE_ML_ENDPOINT_KEY and restart the container."),
            )
        return HealthResponse(status="ok", model_loaded=False, inference_mode="remote")

    # Local mode
    model_loaded = getattr(app.state, "model", None) is not None
    if not model_loaded:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Model is not loaded. Container is not ready for traffic.",
        )
    return HealthResponse(status="ok", model_loaded=True, inference_mode="local")


